"""Report generation (Markdown + JSON)."""

import json
from datetime import datetime, timezone
from pathlib import Path
from typing import Dict, Any, List, Optional


def generate_report(
    device_info: Dict[str, str],
    mvt_result: Optional[Dict[str, Any]] = None,
    profiles: Optional[List[Dict[str, Any]]] = None,
    apps: Optional[List[Dict[str, str]]] = None,
    suspicious_apps: Optional[List[Dict[str, str]]] = None,
    output_dir: Path = Path("reports"),
) -> Dict[str, Path]:
    """
    Write Markdown and JSON reports. Returns paths to the written files.
    """
    output_dir = Path(output_dir)
    output_dir.mkdir(parents=True, exist_ok=True)

    ts = datetime.now(timezone.utc).strftime("%Y%m%dT%H%M%SZ")
    udid = device_info.get("UniqueDeviceID", "unknown")[:12]
    base = output_dir / f"ios-audit-{udid}-{ts}"

    # JSON
    payload = {
        "timestamp_utc": ts,
        "device": device_info,
        "mvt": mvt_result or {},
        "profiles": profiles or [],
        "apps_count": len(apps) if apps else 0,
        "suspicious_apps": suspicious_apps or [],
    }
    json_path = base.with_suffix(".json")
    json_path.write_text(json.dumps(payload, indent=2, default=str))

    # Markdown
    md_lines = [
        f"# Ghostprint — iOS Security Audit Report",
        f"",
        f"**Generated (UTC):** {ts}",
        f"",
        f"## Device Summary",
        f"",
        f"| Field | Value |",
        f"|-------|-------|",
    ]
    for k, v in device_info.items():
        md_lines.append(f"| {k} | {v} |")

    md_lines.extend(["", "## MVT / Spyware IOC Results", ""])
    if mvt_result:
        detected = mvt_result.get("detected_iocs", False)
        md_lines.append(f"- **IOCs detected:** {'YES – review carefully' if detected else 'No known IOCs found'}")
        md_lines.append(f"- **Findings count:** {len(mvt_result.get('findings', []))}")
        md_lines.append(f"- **MVT success:** {mvt_result.get('success')}")
        if mvt_result.get("findings"):
            md_lines.append("")
            md_lines.append("### Detected Indicators")
            for f in mvt_result["findings"][:50]:  # limit
                md_lines.append(f"- `{json.dumps(f)[:200]}...`")
    else:
        md_lines.append("_MVT was not run or results unavailable._")

    md_lines.extend(["", "## Configuration Profiles", ""])
    if profiles:
        for p in profiles:
            risk = p.get("risk", "UNKNOWN")
            md_lines.append(f"- **{p.get('payload_display_name', 'Unknown')}** (risk: {risk})")
            md_lines.append(f"  - Identifier: `{p.get('payload_identifier', 'N/A')}`")
            md_lines.append(f"  - Path: `{p.get('path', 'N/A')}`")
    else:
        md_lines.append("_No profiles extracted or none found._")

    md_lines.extend(["", "## Apps", ""])
    md_lines.append(f"- Total listed: {len(apps) if apps else 0}")
    if suspicious_apps:
        md_lines.append(f"- **Suspicious (heuristic):** {len(suspicious_apps)}")
        for a in suspicious_apps:
            md_lines.append(f"  - `{a.get('identifier')}` – {a.get('reason')}")
    else:
        md_lines.append("- No suspicious apps flagged by basic heuristics.")

    md_lines.extend([
        "",
        "## Recommendations",
        "",
        "1. If any IOCs were detected, treat the device as potentially compromised.",
        "2. Review and remove unknown configuration profiles immediately.",
        "3. Consider a full erase + set-up as new (avoid restoring from a possibly tainted backup).",
        "4. Change Apple ID password and review trusted devices from a clean computer.",
        "5. Keep iOS fully updated.",
        "",
        "---",
        "*Report generated by Ghostprint (ios-security-auditor) – for consensual use only.*",
    ])

    md_path = base.with_suffix(".md")
    md_path.write_text("\n".join(md_lines))

    return {"markdown": md_path, "json": json_path}
